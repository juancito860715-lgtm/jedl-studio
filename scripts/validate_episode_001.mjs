import { readFileSync, existsSync, mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';

const root='producciones/episodio_001';
const html=readFileSync(`${root}/index.html`,'utf8');
const script=JSON.parse(readFileSync(`${root}/guion.json`,'utf8'));
const licenses=readFileSync(`${root}/LICENCIAS.md`,'utf8');
assert.equal(script.duration_seconds,30);
assert.equal(script.shots.length,8);
assert.equal(script.dialogue.length,5);
assert.equal(script.cast.length,2);
assert.ok(html.includes('<svg id="art"'),'Falta ilustración SVG integrada');
assert.ok(html.includes('function shotAt(t)'),'Falta cámara/encuadres animados');
assert.ok(html.includes('function pose(t,who)'),'Falta actuación de personajes');
assert.ok(html.includes('new SpeechSynthesisUtterance'),'Falta síntesis de voz del navegador');
assert.ok(html.includes('aria-live="polite"'),'Faltan subtítulos accesibles');
assert.ok(html.includes('requestAnimationFrame(tick)'),'Falta reloj de reproducción');
assert.ok(html.includes('elapsedBeforePause=0'),'Falta estado de pausa/reanudación');
assert.ok(html.includes('startAt=performance.now()-elapsedBeforePause*1000'),'La reanudación debe conservar el tiempo transcurrido');
assert.ok(html.includes("document.addEventListener('visibilitychange'"),'Falta gestión al cambiar de pestaña o aplicación');
assert.ok(html.includes('if(active)spoken.delete(active.t)'),'La línea de diálogo interrumpida debe poder reproducirse al reanudar');
assert.ok(html.includes("$('start').addEventListener('click',()=>start(false))"),'El botón principal debe continuar desde la posición guardada');
assert.ok(html.includes("$('again').addEventListener('click',()=>start(true))"),'El botón de repetir debe reiniciar desde cero');
assert.equal(script.runtime.external_libraries,false,'No debe requerir bibliotecas externas');
assert.equal(script.runtime.external_assets,false,'No debe requerir recursos externos');
assert.ok(!html.includes('three.module.js'),'No debe depender de Three.js CDN');
assert.ok(!html.includes('GLTFLoader'),'No deben existir descargas GLB');
assert.ok(licenses.includes('originales creados'),'Falta procedencia del arte');
assert.ok(existsSync(`${root}/README.md`),'Falta README');
const a=html.indexOf('<script>'),b=html.indexOf('</script>',a+1);
assert.ok(a>=0&&b>a,'No se encontró JavaScript');
const dir=mkdtempSync(join(tmpdir(),'jedl-episode-')),file=join(dir,'episode.js');
try{writeFileSync(file,html.slice(a+8,b));const check=spawnSync(process.execPath,['--check',file],{encoding:'utf8'});assert.equal(check.status,0,check.stderr||check.stdout)}finally{rmSync(dir,{recursive:true,force:true})}
console.log('OK: episodio 30 s, arte SVG integrado, 8 planos, 5 diálogos, reparto, animación, subtítulos y sintaxis JS.');
console.log('NOTA: la prueba estática no sustituye la reproducción visual y auditiva en Safari/iPhone.');
