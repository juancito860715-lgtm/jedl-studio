import { readFileSync, existsSync, mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';

const root='producciones/episodio_001';
const html=readFileSync(`${root}/index.html`,'utf8');
const script=JSON.parse(readFileSync(`${root}/guion.json`,'utf8'));
const licenses=readFileSync(`${root}/LICENCIAS.md`,'utf8');
assert.equal(script.duration_seconds,30);
assert.equal(script.shots.length,8);
assert.equal(script.dialogue.length,5);
assert.equal(script.cast.length,2);
assert.ok(html.includes('new THREE.PerspectiveCamera'),'Falta cámara Three.js');
assert.ok(html.includes('function cameraAt(t)'),'Falta cámara con planos');
assert.ok(html.includes('function animate(t)'),'Falta actuación procedural');
assert.ok(html.includes('function makePerson(kind,x,z)'),'Faltan personajes locales');
assert.ok(html.includes('const bench=new THREE.Group()'),'Falta banco de trabajo local');
assert.ok(html.includes('new SpeechSynthesisUtterance'),'Falta voz del navegador');
assert.ok(html.includes('voiceschanged'),'Falta detección asíncrona de voces');
assert.ok(html.includes('subtitle.textContent'),'Faltan subtítulos');
assert.ok(html.includes('requestAnimationFrame(tick)'),'Falta reloj de reproducción');
assert.equal(script.runtime.external_3d_assets,false,'El guion debe declarar que no hay modelos externos');
assert.ok(!html.includes('GLTFLoader'),'No deben existir descargas GLB');
assert.ok(!html.includes('GrandmaShopper'),'No debe reutilizarse el modelo de casting incorrecto');
assert.ok(!html.includes('Schoolkid.glb'),'No debe depender del modelo externo de aprendiz');
assert.ok(licenses.includes('MIT'),'Falta atribución de Three.js');
assert.ok(existsSync(`${root}/README.md`),'Falta README');
const a=html.indexOf('<script type="module">'),b=html.indexOf('</script>',a+1);
assert.ok(a>=0&&b>a,'No se encontró módulo JavaScript');
const dir=mkdtempSync(join(tmpdir(),'jedl-episode-')),file=join(dir,'episode.mjs');
try{writeFileSync(file,html.slice(a+'<script type="module">'.length,b));const check=spawnSync(process.execPath,['--check',file],{encoding:'utf8'});assert.equal(check.status,0,check.stderr||check.stdout)}finally{rmSync(dir,{recursive:true,force:true})}
console.log('OK: guion 30 s, 8 planos, 5 diálogos, reparto correcto, banco y taller locales, voz/subtítulos y sintaxis JS.');
console.log('NOTA: la prueba estática no sustituye la reproducción real en Safari/iPhone.');
