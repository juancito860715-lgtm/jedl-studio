#!/usr/bin/env python3
"""Build JEDL hybrid style: generated rig body + original RGS idle components.

RGS artwork is copied as complete RGBA files. No segmentation, trimming, or
geometric reconstruction is performed. Attachment points are explicit policy
values and are emitted into the style manifest.
"""
import argparse
import json
import shutil
from pathlib import Path
from PIL import Image

RGS_ROOT_NAME = "Free 2D Animated Vector Game Character Sprites/Animated body parts"
RIG_BONES = {"torso", "head", "armUL", "foreArmL", "armUR", "foreArmR",
             "thighL", "shinL", "thighR", "shinR"}

# source path relative to extracted archive, destination id, Kotlin slot, bone,
# z-order, measured pivot key. Coordinates are measured in the full PNG canvas.
RGS_PARTS = [
    ("Heads/head1/idle_0.png", "rgs_head_skin", "HEAD", "head", 10, "head", "head"),
    ("Eyes/eyes1/idle_0.png", "rgs_face_eyes_dots", "EYES", "head", 20, "eyes", "overlay"),
    ("Mouths/mouth1/idle_0.png", "rgs_face_mouth_smile", "MOUTH", "head", 22, "mouth", "overlay"),
    ("Hairs/hair1/idle_0.png", "rgs_hair_short_front", "HAIR_FRONT", "head", 30, "hair", "overlay"),
    ("Left hands/handL1/idle_0.png", "rgs_hand_l", "HAND_L", "foreArmL", 60, "hand_l", "fit"),
    ("Right hands/handR1/idle_0.png", "rgs_hand_r", "HAND_R", "foreArmR", 61, "hand_r", "fit"),
    ("Left feet/footL1/idle_0.png", "rgs_shoe_l", "SHOE_L", "shinL", 18, "foot_l", "fit"),
    ("Right feet/footR1/idle_0.png", "rgs_shoe_r", "SHOE_R", "shinR", 19, "foot_r", "fit"),
]


def png_metrics(path: Path):
    with Image.open(path) as image:
        rgba = image.convert("RGBA")
        alpha = rgba.getchannel("A")
        bbox = alpha.getbbox()
        if bbox is None:
            raise ValueError(f"RGS image is fully transparent: {path}")
        return rgba.size, bbox


def normalized_fit(size, target_width, target_height):
    w, h = size
    scale = min(target_width / w, target_height / h)
    return round(w * scale, 6), round(h * scale, 6)



def render_preview(output: Path, manifest: dict):
    """Render a deterministic neutral front-view assembly from rig joint anchors."""
    from PIL import ImageDraw
    joints = {
        "torso": (0.0, 0.0), "head": (0.0, -0.28),
        "armUL": (-0.10, -0.26), "foreArmL": (-0.10, -0.115),
        "armUR": (0.10, -0.26), "foreArmR": (0.10, -0.115),
        "thighL": (-0.07, -0.02), "shinL": (-0.07, 0.17),
        "thighR": (0.07, -0.02), "shinR": (0.07, 0.17),
    }
    scale, center = 500, (512, 380)
    canvas = Image.new("RGBA", (1024, 900), (245, 247, 250, 255))
    ordered = sorted((p for p in manifest["parts"] if manifest["defaults"].get(p["slot"]) == p["id"]),
                     key=lambda p: p["zIndex"])
    for part in ordered:
        path = output / part["file"]
        with Image.open(path) as source:
            sprite = source.convert("RGBA")
        draw_w = max(1, round(part["widthUnits"] * scale))
        draw_h = max(1, round(part["heightUnits"] * scale))
        sprite = sprite.resize((draw_w, draw_h), Image.Resampling.LANCZOS)
        jx, jy = joints[part["boneId"]]
        anchor_x = center[0] + jx * scale
        anchor_y = center[1] + jy * scale
        x = round(anchor_x - part["pivotX"] * draw_w)
        y = round(anchor_y - part["pivotY"] * draw_h)
        canvas.alpha_composite(sprite, (x, y))
    ImageDraw.Draw(canvas).text((24, 24), "JEDL HYBRID RGS — AUTOMATED RIG PREVIEW",
                                fill=(25, 35, 50, 255))
    canvas.convert("RGB").save(output / "hybrid_preview.png", quality=95)
    print(f"HYBRID_VISUAL_PREVIEW={output / 'hybrid_preview.png'}")


def build(rgs_root: Path, source_manifest: Path, source_png_dir: Path, output: Path, pivots_path: Path):
    if not rgs_root.is_dir():
        raise FileNotFoundError(f"RGS extraction root missing: {rgs_root}")
    source = json.loads(source_manifest.read_text(encoding="utf-8"))
    if not pivots_path.is_file():
        raise FileNotFoundError(f"Measured pivot file missing: {pivots_path}; run tools/auto_pivot.py first")
    measured_pivots = json.loads(pivots_path.read_text(encoding="utf-8"))
    if source.get("rigId") != "jedl_humanoid_v1" or set(source.get("rigBones", [])) != RIG_BONES:
        raise ValueError("Generated body manifest does not match JEDL humanoid rig")
    parts = [dict(p) for p in source["parts"]]
    defaults = dict(source["defaults"])
    by_id = {p["id"]: p for p in parts}
    if len(by_id) != len(parts):
        raise ValueError("Duplicate source piece IDs")

    # Body remains generated by build.py. Replace only face/head overlays,
    # hands, and shoes with original RGS artwork.
    required_slots = {"HEAD", "EYES", "MOUTH", "HAIR_FRONT", "HAND_L", "HAND_R", "SHOE_L", "SHOE_R"}
    if not required_slots.issubset(defaults):
        raise ValueError(f"Body manifest lacks required defaults: {sorted(required_slots - set(defaults))}")
    # Keep generated alternatives as selectable variants; RGS pieces become defaults.
    character_dir = output / "characters"
    character_dir.mkdir(parents=True, exist_ok=True)
    source_prefix = rgs_root / RGS_ROOT_NAME
    copied = []
    head_metrics = None
    body_head = by_id[defaults["HEAD"]]
    body_hand = next(p for p in by_id.values() if p["slot"] == "HAND_L")
    body_shoe = next(p for p in by_id.values() if p["slot"] == "SHOE_L")

    # Require shared full-canvas dimensions for head/eyes/mouth/hair so
    # transparent offsets remain aligned exactly as authored by RGS.
    overlay_size = None
    for relative, part_id, slot, bone, z, pivot_key, mode in RGS_PARTS:
        src = source_prefix / relative
        if not src.is_file():
            raise FileNotFoundError(f"Required RGS idle sprite missing: {src}")
        size, bbox = png_metrics(src)
        if mode == "head":
            overlay_size = size
            head_metrics = (size, bbox)
        elif mode == "overlay" and size != overlay_size:
            raise ValueError(
                f"RGS face canvas mismatch for {relative}: {size} != head canvas {overlay_size}; "
                "refusing to shift facial features automatically"
            )
        if pivot_key not in measured_pivots:
            raise KeyError(f"Measured pivot not found: {pivot_key}")
        pivot = measured_pivots[pivot_key]
        px, py = float(pivot["pivotX"]), float(pivot["pivotY"])
        dest_name = f"{part_id}.png"
        dest = character_dir / dest_name
        shutil.copy2(src, dest)
        if mode in ("head", "overlay"):
            width_units = float(body_head["widthUnits"])
            height_units = width_units * size[1] / size[0]
            if mode == "head":
                # Preserve generated head's target dimensions and scale the RGS
                # sprite uniformly to fit that same rig-space footprint.
                height_units = float(body_head["heightUnits"])
                width_units = height_units * size[0] / size[1]
                width_units = min(width_units, float(body_head["widthUnits"]))
                height_units = width_units * size[1] / size[0]
        else:
            target = body_hand if slot.startswith("HAND") else body_shoe
            width_units, height_units = normalized_fit(size, float(target["widthUnits"]) * 2.8,
                                                       float(target["heightUnits"]) * 2.8)
        item = {
            "id": part_id, "slot": slot, "boneId": bone,
            "file": f"{'characters' if part_id.startswith('rgs_') else 'png'}/{dest_name}",
            "pivotX": float(px), "pivotY": float(py),
            "widthUnits": round(width_units, 6), "heightUnits": round(height_units, 6),
            "zIndex": int(z), "offsetX": 0.0, "offsetY": 0.0,
        }
        parts.append(item)
        defaults[slot] = part_id
        copied.append({"source": relative, "file": item["file"], "slot": slot,
                       "boneId": bone, "dimensionsPx": list(size), "alphaBounds": list(bbox),
                       "pivot": [px, py], "pivotMeasurement": pivot})

    # Validate every file, slot, bone, ID and default before publishing.
    ids = [p["id"] for p in parts]
    if len(ids) != len(set(ids)):
        raise ValueError("Hybrid manifest contains duplicate piece IDs")
    for p in parts:
        if p["boneId"] not in RIG_BONES:
            raise ValueError(f"Invalid bone {p['boneId']} for {p['id']}")
        if not (0 <= p["pivotX"] <= 1 and 0 <= p["pivotY"] <= 1):
            raise ValueError(f"Invalid normalized pivot for {p['id']}")
        if p["widthUnits"] <= 0 or p["heightUnits"] <= 0:
            raise ValueError(f"Invalid dimensions for {p['id']}")
        if not (output / p["file"]).is_file() and not (source_png_dir / Path(p["file"]).name).is_file():
            raise FileNotFoundError(f"Missing hybrid PNG for {p['id']}")
    by_id = {p["id"]: p for p in parts}
    for slot, part_id in defaults.items():
        if part_id not in by_id or by_id[part_id]["slot"] != slot:
            raise ValueError(f"Invalid hybrid default: {slot} -> {part_id}")

    # Copy unchanged generated body pieces and all remaining variants.
    for p in parts:
        dest = output / p["file"]
        if not dest.exists():
            source_png = source_png_dir / f'{p["id"]}.png'
            if not source_png.is_file():
                raise FileNotFoundError(f"Generated body PNG missing: {source_png}")
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source_png, dest)

    manifest = dict(source)
    manifest.update({"id": "jedl_hybrid_rgs_v1", "parts": sorted(parts, key=lambda p: (p["zIndex"], p["id"])),
                     "defaults": defaults,
                     "source": {"body": "JEDL Python avatar_bank/build.py",
                                "faceHandsFeet": "RGS_Dev CC0 pack; idle_0.png"}})
    output.mkdir(parents=True, exist_ok=True)
    manifest_path = output / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (output / "rgs_mapping_report.json").write_text(
        json.dumps({"copied": copied, "count": len(copied)}, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")
    print(f"HYBRID_RGS_PARTS={len(copied)}")
    print(json.dumps(copied, indent=2, ensure_ascii=False))
    print(f"HYBRID_MANIFEST={manifest_path}")
    render_preview(output, manifest)
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rgs-root", default="temp_rgs")
    parser.add_argument("--source-manifest", default="tools/avatar_bank/out/manifest.json")
    parser.add_argument("--source-png-dir", default="tools/avatar_bank/out/png")
    parser.add_argument("--output", default="app/src/main/assets/styles/hybrid")
    parser.add_argument("--pivots", default="rgs_auto_pivots.json")
    args = parser.parse_args()
    build(Path(args.rgs_root), Path(args.source_manifest), Path(args.source_png_dir), Path(args.output), Path(args.pivots))


if __name__ == "__main__":
    main()
